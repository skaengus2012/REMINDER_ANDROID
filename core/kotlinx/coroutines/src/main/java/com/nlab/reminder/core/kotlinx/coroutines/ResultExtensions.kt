package com.nlab.reminder.core.kotlinx.coroutines

import kotlin.coroutines.cancellation.CancellationException

/**
 * Like [runCatching], but rethrows [CancellationException] to keep coroutine cancellation cooperative.
 * Only [Exception] is wrapped into [Result.failure]; [Error] is propagated.
 */
inline fun <T> suspendRunCatching(block: () -> T): Result<T> =
    try {
        Result.success(block())
    } catch (e: CancellationException) {
        throw e
    } catch (e: Exception) {
        Result.failure(e)
    }
